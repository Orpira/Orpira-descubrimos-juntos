"""End-to-end acceptance for a running review build."""
import os
from playwright.sync_api import expect, sync_playwright

base = os.environ.get("TEST_BASE", "http://localhost:4321")
with sync_playwright() as p:
    options = {"executable_path": os.environ["CHROMIUM"]} if "CHROMIUM" in os.environ else {}
    browser = p.chromium.launch(**options)
    context = browser.new_context(viewport={"width": 390, "height": 844}, accept_downloads=True)
    context.grant_permissions(["clipboard-read", "clipboard-write"])
    page = context.new_page()
    errors = []
    page.set_default_timeout(7000)
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(base)
    page.wait_for_function("navigator.serviceWorker.controller !== null")
    page.locator("astro-island[ssr]").wait_for(state="detached")
    expect(page.locator(".card")).to_have_count(10)
    assert page.evaluate("document.documentElement.scrollWidth === innerWidth")
    page.get_by_label("Mundo", exact=True).select_option("Ingeniería")
    page.get_by_label("Edad orientativa").select_option("6")
    expect(page.locator(".card")).to_have_count(1)
    page.get_by_role("link", name="El puente imposible").click()
    expect(page.get_by_role("heading", name="El puente imposible")).to_be_visible()
    qr = page.get_by_role("img", name="QR de acceso a El puente imposible")
    expect(qr).to_be_visible()
    assert qr.evaluate("img => img.complete && img.naturalWidth > 0")
    page.get_by_role("checkbox").first.check()
    page.get_by_role("button", name="Guardar pasos en este dispositivo").click()
    page.get_by_role("button", name="Guardar favorito").click()
    page.get_by_role("button", name="Añadir sello al pasaporte").click()
    page.get_by_role("button", name="Guardar sin conexión").click()
    expect(page.get_by_role("button", name="Eliminar descarga")).to_be_visible()
    page.evaluate("window.print = () => { window.printInvoked = true; }")
    page.get_by_role("button", name="Imprimir ficha").click()
    assert page.evaluate("window.printInvoked")
    page.emulate_media(media="print")
    expect(page.get_by_role("button", name="Imprimir ficha")).to_be_hidden()
    page.emulate_media(media="screen")
    page.get_by_role("button", name="Compartir ficha").click()
    expect(page.get_by_role("status")).to_have_text("Enlace copiado.")
    assert page.evaluate("navigator.clipboard.readText()") == base + "/aventuras/el-puente-imposible/"

    page.goto(base + "/pasaporte/")
    page.locator("#collection-world").select_option("Tecnología")
    page.get_by_role("button", name="Guardar colección sin conexión").click()
    expect(page.get_by_role("status")).to_have_text("Colección disponible sin conexión.")
    expect(page.locator('[data-section="2"] li:visible')).to_have_count(3)

    context.set_offline(True)
    page.goto(base + "/pasaporte/")
    expect(page.get_by_role("link", name="El puente imposible")).to_have_count(3)
    page.locator('[data-section="2"]').get_by_role("link", name="El puente imposible").click()
    expect(page.get_by_role("checkbox").first).to_be_checked()
    page.get_by_role("button", name="Reiniciar pasos").click()
    expect(page.get_by_role("checkbox").first).not_to_be_checked()
    assert page.locator(".detail-image").evaluate("img => img.complete && img.naturalWidth > 0")
    page.goto(base + "/aventuras/nuestra-orquesta/")
    expect(page.get_by_role("heading", name="Ficha no disponible")).to_be_visible()

    page.goto(base + "/comunidad/")
    page.get_by_role("button", name="Calcular materiales").click()
    expect(page.get_by_role("status")).to_contain_text("3 equipos de 4 personas")
    expect(page.get_by_role("status")).to_contain_text("Papel: 6 en total")
    expect(page.get_by_role("heading", name="Programa de ocho sesiones")).to_be_visible()
    page.goto(base + "/privacidad/")
    page.once("dialog", lambda dialog: dialog.accept())
    page.get_by_role("button", name="Eliminar progreso, favoritos y descargas").click()
    expect(page.get_by_role("status")).to_have_text("Progreso, favoritos y fichas eliminados.")
    page.goto(base + "/pasaporte/")
    expect(page.get_by_text("Aún no hay fichas en esta sección.")).to_have_count(3)
    with page.expect_download() as exported:
        page.get_by_role("button", name="Exportar pasaporte").click()
    assert exported.value.suggested_filename == "pasaporte.json"
    page.set_viewport_size({"width": 1280, "height": 800})
    page.goto(base)
    expect(page.locator(".card")).to_have_count(10)
    page.keyboard.press("Tab")
    expect(page.get_by_role("link", name="Saltar al contenido")).to_be_focused()
    assert errors == [], errors
    browser.close()
    print("OK: catálogo, móvil/escritorio, teclado, QR renderizado, progreso, favoritos, sellos, impresión, enlace, fichas y colecciones offline, taller y borrado.")
